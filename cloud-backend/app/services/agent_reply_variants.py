# ---------------------------------------------------------------------------
# 便捷函数：各调用点的统一入口（均幂等、同栏同轮稳定）
# ---------------------------------------------------------------------------
def missing_field_ask(label: str, turn: int = 0) -> str:
    return _pick(label, MISSING_FIELD_ASKS, turn).format(label=label)


def acceptance_procedure_ask(turn: int = 0) -> str:
    return _pick("验收工序", ACCEPTANCE_PROCEDURE_ASKS, turn)


def final_confirm_ask(turn: int = 0) -> str:
    return _pick("最终确认", FINAL_CONFIRM_ASKS, turn)


def final_confirm_tail(turn: int = 0) -> str:
    return _pick("最终确认尾句", FINAL_CONFIRM_TAILS, turn)


def write_through_head(rid: int, rtype: str, turn: int = 0) -> str:
    return _pick(f"#{rid}", WRITE_THROUGH_HEADS, turn).format(rid=rid, rtype=rtype)


def write_through_next_ask(label: str, hint: str, turn: int = 0) -> str:
    return _pick(label, WRITE_THROUGH_NEXT_ASKS, turn).format(label=label, hint=hint)


def field_hint_head(label: str, hint: str, turn: int = 0) -> str:
    return _pick(label, FIELD_HINT_HEADS, turn).format(label=label, hint=hint)


def auto_skip_tail(label: str, turn: int = 0) -> str:
    return _pick(label, AUTO_SKIP_TAILS, turn).format(label=label)


def created_tail(turn: int = 0) -> str:
    return _pick("建单尾句", CREATED_TAILS, turn)


def tbd_tail(turn: int = 0) -> str:
    return _pick("待定尾句", TBD_TAILS, turn)
