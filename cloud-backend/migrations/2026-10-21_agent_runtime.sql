-- Durable agent request traces and idempotent execution instances.
-- Apply with a database account that owns schema/DDL privileges.

CREATE TABLE IF NOT EXISTS agent_request_traces (
  id INT NOT NULL AUTO_INCREMENT,
  request_id VARCHAR(80) NOT NULL,
  user_id INT NOT NULL,
  project_id INT NULL,
  conversation_id VARCHAR(64) NULL,
  endpoint VARCHAR(80) NOT NULL,
  status VARCHAR(24) NOT NULL,
  current_stage VARCHAR(64) NOT NULL,
  message_excerpt TEXT NOT NULL,
  provider VARCHAR(80) NOT NULL,
  model VARCHAR(160) NOT NULL,
  request_plan_json TEXT NOT NULL,
  stages_json TEXT NOT NULL,
  result_json TEXT NOT NULL,
  error_stage VARCHAR(64) NOT NULL,
  error_message TEXT NOT NULL,
  review_plan_id INT NULL,
  created_record_refs_json TEXT NOT NULL,
  started_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  finished_at DATETIME NULL,
  duration_ms INT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ix_agent_request_traces_request_id (request_id),
  KEY ix_agent_request_traces_user_id (user_id),
  KEY ix_agent_request_traces_project_id (project_id),
  KEY ix_agent_request_traces_status (status),
  KEY ix_agent_request_traces_review_plan_id (review_plan_id),
  KEY ix_agent_request_traces_started_at (started_at),
  KEY ix_agent_request_traces_updated_at (updated_at),
  KEY ix_agent_request_traces_user_project (user_id, project_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS agent_flow_instances (
  id INT NOT NULL AUTO_INCREMENT,
  execution_id VARCHAR(160) NOT NULL,
  request_id VARCHAR(80) NULL,
  flow_type VARCHAR(48) NOT NULL,
  scope_id VARCHAR(160) NOT NULL,
  user_id INT NOT NULL,
  project_id INT NOT NULL,
  conversation_id VARCHAR(64) NULL,
  expected_revision INT NULL,
  status VARCHAR(20) NOT NULL,
  stage VARCHAR(64) NOT NULL,
  attempts INT NOT NULL,
  result_json TEXT NOT NULL,
  error_message TEXT NOT NULL,
  started_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  finished_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY ix_agent_flow_instances_execution_id (execution_id),
  KEY ix_agent_flow_instances_request_id (request_id),
  KEY ix_agent_flow_instances_user_id (user_id),
  KEY ix_agent_flow_instances_project_id (project_id),
  KEY ix_agent_flow_instances_status (status),
  KEY ix_agent_flow_instances_updated_at (updated_at),
  KEY ix_agent_flow_instances_user_project (user_id, project_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
